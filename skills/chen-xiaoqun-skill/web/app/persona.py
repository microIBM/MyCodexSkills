import os as _os

from app import config as _config

_full_cache: str | None = None


def get_system_prompt(mode: str) -> str:
    if mode != "full":
        return VOICE_SYSTEM_PROMPT
    global _full_cache
    if _full_cache is None:
        path = _os.path.join(_os.path.dirname(_config.BASE_DIR), "SKILL.md")
        try:
            with open(path, encoding="utf-8") as f:
                _full_cache = VOICE_PREFIX + f.read() + VOICE_RULES_APPENDIX
        except OSError:
            return VOICE_SYSTEM_PROMPT  # 不缓存失败结果，SKILL.md 补上后即恢复
    return _full_cache
